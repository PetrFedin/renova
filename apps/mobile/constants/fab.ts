/**
 * Геометрия плавающей кнопки быстрых действий — и запас, который она требует
 * от экранов.
 *
 * Кнопка смонтирована один раз в `OsRoleTabsNavigator`, то есть лежит поверх
 * содержимого **всех** вкладок обеих ролей. Значит нижняя часть каждой
 * прокручиваемой вкладки уходит под неё, и экраны обязаны оставить свободное
 * место.
 *
 * Раньше не оставляли. Измерено на 375×812: кнопка занимает снизу 88 + 52 =
 * 140 точек, а запас у главной был `paddingBottom: 24`. Под центром кнопки
 * лежала кнопка-ссылка «Сроки →» — нажатие туда открывало меню быстрых
 * действий вместо раздела «Сроки».
 *
 * Значения живут здесь, а не в компоненте, чтобы от них могли зависеть
 * отступы экранов без импорта компонента в модуль констант.
 */
import { Platform } from 'react-native';

export const FAB_SIZE = 52;
export const FAB_RIGHT = 16;
/** Отступ от низа экрана: на вебе выше, там нижняя панель толще. */
export const FAB_BOTTOM = Platform.OS === 'web' ? 88 : 76;
/** Сколько нижнего пространства прокручиваемый экран обязан оставить пустым. */
export const FAB_SAFE_BOTTOM = FAB_BOTTOM + FAB_SIZE + 12;
