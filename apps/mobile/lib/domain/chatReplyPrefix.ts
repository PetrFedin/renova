/**
 * Ответ в чате хранится дважды: связью `reply_to_id` и строкой «↩ …» в самом
 * тексте. Строка нужна там, где связь не разворачивается — в выгрузке чата, в
 * поиске по сообщениям и в пуш-уведомлении. На экране, где цитата показана
 * отдельным блоком, та же строка дублирует её.
 *
 * Поэтому её убирают из показа, а не из сообщения.
 */
export function textWithoutReplyPrefix(text: string, hasQuote: boolean): string {
  if (!hasQuote) return text;
  const stripped = text.replace(/^↩[^\n]*\n/, '');
  // Сообщение, состоящее из одной строки «↩ …», не должно стать пустым.
  return stripped || text;
}
