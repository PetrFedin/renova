/**
 * Текст «Нет сети»: подпись — существительное любого рода («Счёт», «Приёмка», «Фиксация сметы»),
 * поэтому подставляем её в «Действие «…»» (иначе «Приёмка поставлено в очередь»).
 */
export function offlineQueuedMessage(actionLabel = 'Действие'): string {
  const subject = actionLabel === 'Действие' ? 'Действие' : `Действие «${actionLabel}»`;
  return `${subject} поставлено в очередь и выполнится при появлении интернета. Не закрывайте приложение сразу.`;
}
